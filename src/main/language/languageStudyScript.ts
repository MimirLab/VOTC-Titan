/** Shared authoring/capture contract for the local Titan component. Workshop files stay untouched. */
export function studyVariable(language: string): string {
    if (!/^language_[a-zA-Z0-9_]+$/.test(language)) throw new Error('Invalid studied language');
    return 'votc_titan_study_' + language;
}

export function languageStudyEffects(languages: readonly string[]): string {
    if (!languages.length || new Set(languages).size !== languages.length) throw new Error('Invalid study inventory');
    const remember = [...languages].sort().map(language => {
        const variable = studyVariable(language);
        return `if = { limit = { $TARGET$.culture = { has_cultural_pillar = ${language} } }\n` +
            `if = { limit = { NOT = { has_variable = ${variable} } } set_variable = { name = ${variable} value = $PROGRESS$ } }\n` +
            `else_if = { limit = { var:${variable} < $PROGRESS$ } set_variable = { name = ${variable} value = $PROGRESS$ } }\n}`;
    }).join('\n');
    return '# Generated by tools/build-language-study.cjs from the accepted language inventory.\n' +
        '# Sparse per-character peaks; no scheme, success chance, language knowledge or relationship is changed.\n' +
        'votc_titan_remember_language_study_effect = {\n' + remember + '\n}\n\n' +
        '# Character scope. Called for the player by existing study events, and for NPCs only by chat capture.\n' +
        'votc_titan_observe_language_study_effect = {\nevery_scheme = { type = learn_language\n' +
        'if = { limit = { scheme_phase_duration > 0 exists = scheme_target_character }\n' +
        'save_temporary_scope_value_as = { name = votc_titan_study_fraction value = { value = scheme_progress divide = scheme_phase_duration min = 0 max = 1 } }\n' +
        'scheme_target_character = { save_scope_as = votc_titan_study_target }\n' +
        'scheme_owner = { votc_titan_remember_language_study_effect = { TARGET = scope:votc_titan_study_target PROGRESS = scope:votc_titan_study_fraction } }\n' +
        '}\n}\n}\n\n' + languageStudyLogEffect();
}

/** Expand the existing study observer into CE's command packet. No helper
 * definitions or on_actions need to be installed in a game component.
 */
export function inlineLanguageStudyCapture(languages: readonly string[]): string {
    const source = languageStudyEffects(languages);
    const body = (name: string): string => {
        const prefix = name + ' = {';
        const start = source.indexOf(prefix);
        if (start < 0) throw new Error('Missing language study body.');
        let depth = 1, quoted = false, escaped = false;
        for (let i = start + prefix.length; i < source.length; i++) {
            const c = source[i];
            if (quoted) {
                if (escaped) escaped = false;
                else if (c === '\\') escaped = true;
                else if (c === '"') quoted = false;
            } else if (c === '"') quoted = true;
            else if (c === '{') depth++;
            else if (c === '}' && --depth === 0) return source.slice(start + prefix.length, i);
        }
        throw new Error('Incomplete language study body.');
    };
    const logger = body('votc_titan_log_language_study_effect');
    const header = 'debug_log = "VOTC:LANGUAGE/;/study_begin/;/$LANGUAGE$"';
    if (logger.split(header).length !== 2) throw new Error('Language logger expansion changed.');
    const digits = logger.replace(header, '').replace(/\$PROGRESS\$/g, 'scope:votc_inline_study_value');
    // Current schemes are observed without recording anything in the save.
    // Retained legacy peaks are also read, never manufactured or updated.
    const activeCases = languages.map((language, index) =>
        `${index ? 'else_if' : 'if'} = { limit = { scope:votc_titan_study_target.culture = { has_cultural_pillar = ${language} } }\n` +
        'save_temporary_scope_value_as = { name = votc_inline_study_found value = 1 }\n' +
        header.replace(/\$LANGUAGE\$/g, language) + '\n}').join('\n');
    const active = 'every_scheme = { type = learn_language\n' +
        'if = { limit = { scheme_phase_duration > 0 exists = scheme_target_character }\n' +
        'save_temporary_scope_value_as = { name = votc_inline_study_value value = { value = scheme_progress divide = scheme_phase_duration min = 0 max = 1 } }\n' +
        'scheme_target_character = { save_scope_as = votc_titan_study_target }\n' +
        'scheme_owner = {\n' +
        'save_temporary_scope_value_as = { name = votc_inline_study_found value = 0 }\n' + activeCases + '\n' +
        'if = { limit = { scope:votc_inline_study_found = 1 }\n' + digits + '\n}\n}\n}\n}\n';
    const select = languages.map((language, index) =>
        `${index ? 'else_if' : 'if'} = { limit = { scope:votc_inline_study_cursor <= ${index} has_variable = ${studyVariable(language)} }\n` +
        `save_temporary_scope_value_as = { name = votc_inline_study_cursor value = ${index + 1} }\n` +
        `save_temporary_scope_value_as = { name = votc_inline_study_value value = var:${studyVariable(language)} }\n` +
        'save_temporary_scope_value_as = { name = votc_inline_study_again value = 1 }\n' +
        header.replace(/\$LANGUAGE\$/g, language) + '\n}').join('\n');
    return active +
        'save_temporary_scope_value_as = { name = votc_inline_study_cursor value = 0 }\n' +
        'save_temporary_scope_value_as = { name = votc_inline_study_again value = 1 }\n' +
        'while = { limit = { scope:votc_inline_study_again = 1 }\n' +
        'save_temporary_scope_value_as = { name = votc_inline_study_again value = 0 }\n' + select + '\n' +
        'if = { limit = { scope:votc_inline_study_again = 1 }\n' + digits + '\n}\n}\n' +
        'debug_log = "VOTC:LANGUAGE/;/study_complete"\n';
}

/** One game-side logger avoids repeating fifty digit branches for every language/participant in a console packet. */
function languageStudyLogEffect(): string {
    const digits = Array.from({ length: 5 }, (_, position) =>
        `save_temporary_scope_value_as = { name = votc_study_digit value = { value = scope:votc_study_progress divide = ${10 ** position} floor = yes modulo = 10 } }\n` +
        Array.from({ length: 10 }, (_, digit) => `${digit ? 'else_if' : 'if'} = { limit = { scope:votc_study_digit = ${digit} } ` +
            `debug_log = "VOTC:LANGUAGE/;/study_digit/;/${position}/;/${digit}" }`).join('\n')).join('\n');
    return 'votc_titan_log_language_study_effect = {\n' +
        'save_temporary_scope_value_as = { name = votc_study_progress value = { value = $PROGRESS$ multiply = 10000 min = 0 max = 10000 floor = yes } }\n' +
        'debug_log = "VOTC:LANGUAGE/;/study_begin/;/$LANGUAGE$"\n' + digits + '\n' +
        'debug_log = "VOTC:LANGUAGE/;/study_end"\n}\n';
}

export function languageStudyOnActions(): string {
    return '# Append through private relays; never replace GoA scheme definitions or outcome events.\n' +
        '# These actions already fire for active language schemes. The relay rejects NPCs before doing any study work.\n' +
        'learn_language_ongoing = { on_actions = { votc_titan_study_player_pulse } }\n' +
        'learn_language_success = { on_actions = { votc_titan_study_player_completion } }\n' +
        'learn_language_failure = { on_actions = { votc_titan_study_player_completion } }\n\n' +
        'votc_titan_study_player_pulse = {\ntrigger = { is_ai = no }\neffect = { votc_titan_observe_language_study_effect = yes }\n}\n\n' +
        '# Completion means the full study interval was attempted, even when CK3 rejects fluency.\n' +
        'votc_titan_study_player_completion = {\ntrigger = { is_ai = no exists = scope:target }\n' +
        'effect = { votc_titan_remember_language_study_effect = { TARGET = scope:target PROGRESS = 1 } }\n}\n';
}
